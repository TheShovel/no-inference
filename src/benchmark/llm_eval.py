# Data Structures
# ═════════════════════════════════════════════════════════════════════════════

@dataclass
class JudgeScore:
    """A single judge's score for one response."""
    model: str
    naturalness: int
    informativeness: int
    coherence: int
    correctness: int
    conciseness: int
    raw_response: str = ""  # The raw text the model returned
    parse_error: bool = False  # Whether JSON parsing failed

    @property
    def average(self) -> float:
        """Average across all dimensions."""
        return (self.naturalness + self.informativeness + self.coherence +
                self.correctness + self.conciseness) / 5.0


@dataclass
class EvalResult:
    """Results for one test case across all judges and rounds."""
    query: str
    topic: str
    response: str
    dimension_scores: Dict[str, List[int]] = field(default_factory=lambda: {d: [] for d in DIMENSIONS})
    model_scores: Dict[str, List[float]] = field(default_factory=lambda: {m: [] for m in JUDGE_MODELS})
    round_scores: List[float] = field(default_factory=list)
    all_judgments: List[JudgeScore] = field(default_factory=list)
    num_rounds: int = 0

    @property
    def overall_average(self) -> float:
        """Overall average score across all dimensions and judges."""
        if not self.all_judgments:
            return 0.0
        return sum(j.average for j in self.all_judgments) / len(self.all_judgments)

    @property
    def dimension_averages(self) -> Dict[str, float]:
        """Average score per dimension across all judges."""
        averages = {}
        for dim in DIMENSIONS:
            scores = self.dimension_scores.get(dim, [])
            averages[dim] = sum(scores) / len(scores) if scores else 0.0
        return averages

    def to_dict(self) -> dict:
        """Serialize to dictionary."""
        return {
            "query": self.query,
            "topic": self.topic,
            "response": self.response,
            "overall_average": round(self.overall_average, 2),
            "dimension_averages": {k: round(v, 2) for k, v in self.dimension_averages.items()},
            "num_judgments": len(self.all_judgments),
            "num_rounds": self.num_rounds,
            "judgments": [
                {
                    "model": j.model,
                    "average": round(j.average, 2),
                    "naturalness": j.naturalness,
                    "informativeness": j.informativeness,
                    "coherence": j.coherence,
                    "correctness": j.correctness,
                    "conciseness": j.conciseness,
                    "parse_error": j.parse_error,
                }
                for j in self.all_judgments
            ],
        }


@dataclass
class EvalSummary:
    """Summary across all test cases."""
    results: List[EvalResult] = field(default_factory=list)

    @property
    def overall_average(self) -> float:
        if not self.results:
            return 0.0
        return sum(r.overall_average for r in self.results) / len(self.results)

    @property
    def dimension_averages(self) -> Dict[str, float]:
        averages = {}
        for dim in DIMENSIONS:
            dim_scores = [s for r in self.results for s in r.dimension_scores.get(dim, [])]
            averages[dim] = sum(dim_scores) / len(dim_scores) if dim_scores else 0.0
        return averages

    @property
    def model_averages(self) -> Dict[str, float]:
        model_avgs = {}
        for model in JUDGE_MODELS:
            scores = [s for r in self.results for s in r.model_scores.get(model, [])]
            model_avgs[model] = sum(scores) / len(scores) if scores else 0.0
        return model_avgs

    def to_dict(self) -> dict:
        return {
            "overall_average": round(self.overall_average, 2),
            "dimension_averages": {k: round(v, 2) for k, v in self.dimension_averages.items()},
            "model_averages": {k: round(v, 2) for k, v in self.model_averages.items()},
            "num_results": len(self.results),
            "results": [r.to_dict() for r in self.results],
        }


# ═════════════════════════════════════════════════════════════════════════════
# Ollama API Client
# ═════════════════════════════════════════════════════════════════════════════

def _ollama_generate(model: str, prompt: str, timeout: int = 180) -> Optional[str]:
    """Send a prompt to an Ollama model and get the response text.

    Uses the Ollama HTTP API at http://localhost:11434/api/generate.

    Args:
        model: Model name (e.g., "qwen2.5:0.5b").
        prompt: The full prompt text.
        timeout: Request timeout in seconds.

    Returns:
        Response text string, or None on failure.
    """
    url = f"{OLLAMA_HOST}/api/generate"
    data = json.dumps({
        "model": model,
        "prompt": prompt,
        "stream": False,
        "options": {
            "temperature": 0.3,       # Low temp for stable scores
            "top_p": 0.9,
            "max_tokens": 250,
            "stop": ["\n\n", "```"],
        }
    }).encode('utf-8')

    req = urllib.request.Request(
        url, data=data,
        headers={"Content-Type": "application/json"},
        method="POST"
    )

    try:
        with urllib.request.urlopen(req, timeout=timeout) as resp:
            result = json.loads(resp.read().decode('utf-8'))
            return result.get("response", "")
    except urllib.error.HTTPError as e:
        print(f"      HTTP Error {e.code} for model {model}: {e.reason}")
        return None
    except urllib.error.URLError as e:
        print(f"      Connection error for model {model}: {e.reason}")
        return None
    except json.JSONDecodeError as e:
        print(f"      JSON decode error for model {model}: {e}")
        return None
    except Exception as e:
        print(f"      Unexpected error for model {model}: {e}")
        return None


# ═════════════════════════════════════════════════════════════════════════════
# Scoring Logic
# ═════════════════════════════════════════════════════════════════════════════

def _extract_json_from_response(raw: str) -> Optional[dict]:
    """Extract a JSON object from a model's response text.

    Tries:
      1. Direct JSON parse of the whole response
      2. Find JSON object in the response (between { and })
      3. Find JSON in markdown code blocks

    Returns parsed dict or None.
    """
    if not raw:
        return None

    # Try 1: Direct parse
    raw_stripped = raw.strip()
    try:
        result = json.loads(raw_stripped)
        if isinstance(result, dict):
            return result
    except (json.JSONDecodeError, ValueError):
        pass

    # Try 2: Find JSON object boundaries
    brace_start = raw_stripped.find('{')
    brace_end = raw_stripped.rfind('}')
    if brace_start >= 0 and brace_end > brace_start:
        json_str = raw_stripped[brace_start:brace_end + 1]
        try:
            return json.loads(json_str)
        except json.JSONDecodeError:
            pass

    # Try 3: Extract numbers even without JSON structure
    # Look for patterns like "naturalness: 7"
    scores = {}
    for dim in DIMENSIONS:
        # Pattern: "naturalness: 7" or "naturalness": 7 or "naturalness 7"
        patterns = [
            rf'"{dim}"\s*:\s*(\d+)',
            rf'{dim}\s*[:=]\s*(\d+)',
            rf'{dim}\s+(\d+)',
            rf'{dim}.*?(\d+)',
        ]
        for pat in patterns:
            m = re.search(pat, raw, re.IGNORECASE)
            if m:
                val = int(m.group(1))
                if 1 <= val <= 10:
                    scores[dim] = val
                    break

    if len(scores) >= 3:  # At least 3 of 5 dimensions
        return scores

    return None


def _parse_judge_score(model: str, raw_response: str) -> JudgeScore:
    """Parse a judge's response into a structured score.

    Attempts JSON extraction, then falls back to regex pattern matching.
    """
    parsed = _extract_json_from_response(raw_response)

    if parsed:
        return JudgeScore(
            model=model,
            naturalness=parsed.get("naturalness", 5),
            informativeness=parsed.get("informativeness", 5),
            coherence=parsed.get("coherence", 5),
            correctness=parsed.get("correctness", 5),
            conciseness=parsed.get("conciseness", 5),
            raw_response=raw_response[:200],
            parse_error=False,
        )
    else:
        # Fallback: return mid-range scores
        return JudgeScore(
            model=model,
            naturalness=5,
            informativeness=5,
            coherence=5,
            correctness=5,
            conciseness=5,
            raw_response=raw_response[:200],
            parse_error=True,
        )


def _build_scoring_prompt(response: str) -> str:
    """Build the prompt for the judge model."""
    return SYSTEM_PROMPT.format(
        response=response.replace('"', "'"),
    )


def _score_with_model(model: str, response: str) -> JudgeScore:
    """Get a score from one model for one response."""
    prompt = _build_scoring_prompt(response)
    raw = _ollama_generate(model, prompt)

    if raw is None:
        return JudgeScore(
            model=model, naturalness=0, informativeness=0,
            coherence=0, correctness=0, conciseness=0,
            raw_response="[API ERROR]", parse_error=True,
        )

    return _parse_judge_score(model, raw)


