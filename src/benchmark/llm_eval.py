DIMENSION_DESCRIPTIONS = {
    "naturalness": "How much does this sound like a natural human speaker? 1=robotic, 10=indistinguishable from human",
    "informativeness": "How much meaningful information does it contain? 1=empty/vague, 10=rich in specific facts",
    "coherence": "How well does it flow logically from sentence to sentence? 1=disjointed, 10=smoothly flowing",
    "correctness": "How factually accurate is it? 1=has errors/contradictions, 10=completely accurate",
    "conciseness": "How well does it avoid unnecessary words? 1=too verbose or too brief, 10=perfect length",
}

# Scoring prompt template
SYSTEM_PROMPT = """You are a response quality rater. Rate this response 1-10 on:
- naturalness: sounds human
- informativeness: has facts
- coherence: logical flow
- correctness: accurate
- conciseness: right length

Response: "{response}"

Return ONLY valid JSON like {{"naturalness":7,"informativeness":8,"coherence":6,"correctness":7,"conciseness":5}} with no other text."""


