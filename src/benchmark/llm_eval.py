def main():
    import argparse

    parser = argparse.ArgumentParser(
        description="Multi-LLM Judge for COS NLG Responses"
    )
    parser.add_argument('--dry-run', action='store_true',
                       help="Use mock scores instead of calling LLMs")
    parser.add_argument('--rounds', type=int, default=2,
                       help="Number of judging rounds per response (default: 2)")
    parser.add_argument('--style', choices=['friendly', 'neutral', 'concise'],
                       default='friendly', help="NLG style to evaluate (default: friendly)")
    parser.add_argument('--verbosity', type=float, default=0.5,
                       help="NLG verbosity 0.0-1.0 (default: 0.5)")
    parser.add_argument('--output', type=str, default='data/eval_results.json',
                       help="Output path for results JSON")
    parser.add_argument('--cases', type=int, default=0,
                       help="Number of test cases to run (0=all)")
    parser.add_argument('--quick', action='store_true',
                       help="Quick mode: 1 round, first 3 cases, concise style")
    args = parser.parse_args()

    print(f"\n{'#'*70}")
    print(f"  COS NLG Multi-LLM Evaluation")
    print(f"{'#'*70}")

    if args.quick:
        args.rounds = 1
        args.style = 'concise'
        args.verbosity = 0.3
        print(f"\n  Mode: QUICK (1 round, concise style)")

    # Generate COS responses
    test_cases = PREDEFINED_TEST_CASES
    if args.cases > 0:
        test_cases = test_cases[:args.cases]

    print(f"\n  Generating {len(test_cases)} COS responses (style={args.style}, verbosity={args.verbosity})...")
    responses = generate_cos_responses(test_cases, style=args.style, verbosity=args.verbosity)

    if args.dry_run:
        print(f"\n  DRY RUN — Using mock scores (no LLMs called)")
    else:
        print(f"\n  Judge Models: {', '.join(JUDGE_MODELS)}")
        print(f"  Rounds per response: {args.rounds}")
        print(f"  Total judgments: {len(test_cases) * len(JUDGE_MODELS) * args.rounds}")

    # Run evaluation
    summary = evaluate_responses(
        responses,
        num_rounds=args.rounds,
        dry_run=args.dry_run,
        verbose=True,
    )

    # Print and save results
    print_summary(summary)
    save_results(summary, args.output)

    return 0


