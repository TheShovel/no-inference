"""
LLM Evaluation Framework — Multi-LLM Judge for COS NLG Responses.

Uses multiple tiny LLMs (via Ollama) to evaluate the COS system's responses.
Each model scores 1-10 on 5 dimensions, scores are averaged across models
and rounds for a robust quality score.

Architecture:
  - Test cases: pre-defined query/response pairs or generated by COS
  - Judges: 4 tiny LLMs (smollm2:360m, qwen2.5:0.5b, llama3.2:1b, qwen2.5:1.5b)
  - Dimensions: naturalness, informativeness, coherence, correctness, conciseness
  - Scoring: each model scores each dimension 1-10, scores averaged across models
  - Rounds: multiple rounds for statistical significance

Usage:
    python3 -m src.benchmark.llm_eval --dry-run    # Test without calling LLMs
    python3 -m src.benchmark.llm_eval               # Full evaluation

Requires:
    - Ollama running on localhost:11434
    - Models: smollm2:360m, qwen2.5:0.5b, llama3.2:1b, qwen2.5:1.5b
"""

