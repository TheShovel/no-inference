def generate_cos_responses(test_cases: List[Tuple[str, str, str, str]],
                           style: str = "friendly",
                           verbosity: float = 0.5) -> List[Tuple[str, str, str]]:
    """Generate COS NLG responses for test cases.

    Returns list of (query, topic, response) tuples.
    """
    config = NLGConfig(style=style, verbosity=verbosity, temperature=0.3)
    results = []

    for query, topic, info, intent in test_cases:
        try:
            response = naturalize(query, topic, info, intent, config)
            results.append((query, topic, response))
        except Exception as e:
            print(f"  Error generating response for '{query[:40]}': {e}")
            results.append((query, topic, f"[Error: {e}]"))

    return results


# ═════════════════════════════════════════════════════════════════════════════
# Evaluation Runner
# ═════════════════════════════════════════════════════════════════════════════

def evaluate_responses(
    test_responses: List[Tuple[str, str, str]],
    models: Optional[List[str]] = None,
    num_rounds: int = 2,
    dry_run: bool = False,
    verbose: bool = True,
) -> EvalSummary:
    """Evaluate COS responses using multiple LLM judges.

    For each response, each model judges it `num_rounds` times.
    Scores are aggregated across all models and rounds.

    Args:
        test_responses: List of (query, topic, response) tuples.
        models: List of model names to use as judges.
        num_rounds: Number of judging rounds per response.
        dry_run: If True, use mock scores instead of calling LLMs.
        verbose: If True, print progress.

    Returns:
        EvalSummary containing all results.
    """
    if models is None:
        models = JUDGE_MODELS

    summary = EvalSummary()

    for idx, (query, topic, response) in enumerate(test_responses):
        if verbose:
            print(f"\n  [{idx + 1}/{len(test_responses)}] Evaluating: {query[:50]}...")

        result = EvalResult(query=query, topic=topic, response=response)

        for round_num in range(1, num_rounds + 1):
            if verbose:
                print(f"    Round {round_num}/{num_rounds}")

            round_judgments: List[JudgeScore] = []

            for model in models:
                if dry_run:
                    # Mock scores that vary slightly per round for realism
                    import random
                    base = 7.0
                    noise = random.uniform(-1.0, 1.0)
                    score = max(1, min(10, base + noise))
                    judge = JudgeScore(
                        model=model,
                        naturalness=max(1, min(10, int(score))),
                        informativeness=max(1, min(10, int(score + 0.5))),
                        coherence=max(1, min(10, int(score - 0.3))),
                        correctness=max(1, min(10, int(score + 0.2))),
                        conciseness=max(1, min(10, int(score - 0.5))),
                        raw_response=f"[DRY RUN] score={score:.1f}",
                    )
                else:
                    if verbose:
                        print(f"      {model}...", end=" ", flush=True)
                    judge = _score_with_model(model, response)
                    if verbose:
                        if judge.parse_error:
                            print(f"⚠️  (parse fallback) avg={judge.average:.1f}")
                        else:
                            print(f"avg={judge.average:.1f}")
                    # Small delay to avoid overwhelming Ollama
                    time.sleep(0.5)

                result.all_judgments.append(judge)
                round_judgments.append(judge)

            # Store per-round average
            if round_judgments:
                round_avg = sum(j.average for j in round_judgments) / len(round_judgments)
                result.round_scores.append(round_avg)

        # Aggregate dimension scores
        for judge in result.all_judgments:
            result.dimension_scores["naturalness"].append(judge.naturalness)
            result.dimension_scores["informativeness"].append(judge.informativeness)
            result.dimension_scores["coherence"].append(judge.coherence)
            result.dimension_scores["correctness"].append(judge.correctness)
            result.dimension_scores["conciseness"].append(judge.conciseness)
            if judge.model in result.model_scores:
                result.model_scores[judge.model].append(judge.average)

        result.num_rounds = num_rounds
        summary.results.append(result)

        if verbose:
            print(f"    → Overall: {result.overall_average:.2f} | "
                  f"Dims: {', '.join(f'{k}={v:.1f}' for k, v in result.dimension_averages.items())}")

    return summary


# ═════════════════════════════════════════════════════════════════════════════
# Reporting
# ═════════════════════════════════════════════════════════════════════════════

def print_summary(summary: EvalSummary):
    """Print a formatted summary of evaluation results."""
    print(f"\n{'='*70}")
    print(f"  COS NLG — Multi-LLM Evaluation Results")
    print(f"{'='*70}")
    print(f"\n  Overall Score:         {summary.overall_average:.2f} / 10")
    print(f"  Test Cases:            {len(summary.results)}")
    print(f"  Judge Models:          {', '.join(JUDGE_MODELS)}")
    print(f"  Judgments per case:    {len(summary.results[0].all_judgments) if summary.results else 0}")

    print(f"\n  {'─'*50}")
    print(f"  Dimension Breakdown:")
    print(f"  {'─'*50}")
    for dim in DIMENSIONS:
        avg = summary.dimension_averages.get(dim, 0.0)
        bar = '█' * int(avg) + '░' * (10 - int(avg))
        print(f"    {dim:20s}  {avg:5.2f}  {bar}")

    print(f"\n  {'─'*50}")
    print(f"  Model Breakdown:")
    print(f"  {'─'*50}")
    for model, avg in sorted(summary.model_averages.items(), key=lambda x: -x[1]):
        bar = '█' * int(avg) + '░' * (10 - int(avg))
        print(f"    {model:20s}  {avg:5.2f}  {bar}")

    print(f"\n  {'─'*50}")
    print(f"  Per-Case Results:")
    print(f"  {'─'*50}")
    for i, result in enumerate(summary.results):
        dim_str = ' | '.join(f"{k}={v:.1f}" for k, v in result.dimension_averages.items())
        print(f"    {i+1}. {result.query[:45]:45s}  {result.overall_average:5.2f}")
        print(f"       {dim_str}")

    print(f"\n  {'='*70}")


def save_results(summary: EvalSummary, path: str):
    """Save evaluation results to a JSON file."""
    os.makedirs(os.path.dirname(path) or '.', exist_ok=True)
    with open(path, 'w') as f:
        json.dump(summary.to_dict(), f, indent=2)
    print(f"\n  Results saved to: {path}")


